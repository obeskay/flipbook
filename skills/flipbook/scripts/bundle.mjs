// Concatenates engine/parts/*.js (sorted by filename) into engine/flipbook.js: one IIFE, no globals.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const skillDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const partsDir = join(skillDir, 'engine', 'parts');
const outFile = join(skillDir, 'engine', 'flipbook.js');

const parts = readdirSync(partsDir).filter(f => f.endsWith('.js')).sort();
const body = parts
  .map(f => `// ---- ${f} ----\n${readFileSync(join(partsDir, f), 'utf8').trimEnd()}`)
  .join('\n\n');
const out = [
  '// GENERATED by skills/flipbook/scripts/bundle.mjs from engine/parts/*.js. Do not edit.',
  '(function (root) {',
  "'use strict';",
  body,
  'root.Flipbook = Flipbook;',
  "if (typeof module !== 'undefined') module.exports = Flipbook;",
  '})(globalThis);',
  ''
].join('\n');

writeFileSync(outFile, out);
const bytes = Buffer.byteLength(out);
console.log(`bundled ${parts.length} parts (${parts.join(', ')}) -> engine/flipbook.js: ${bytes} bytes`);
